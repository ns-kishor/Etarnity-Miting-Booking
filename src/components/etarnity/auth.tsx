'use client'

import { useEffect, useState } from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import { api, ApiError } from '@/lib/api-client'
import { navigate } from '@/lib/hash-router'
import type { PlatformSettings } from './types'
import { FieldError } from './ui-bits'
import { toast } from 'sonner'
import { cn } from '@/lib/utils'
import { LogIn, UserPlus, KeyRound, MailQuestion, ArrowLeft, ShieldCheck, Info } from 'lucide-react'

type Mode = 'login' | 'signup' | 'forgot' | 'reset'

const inputCls =
  'w-full rounded-lg border border-input bg-white px-3 py-2.5 text-sm shadow-sm outline-none transition-colors placeholder:text-muted-foreground/50 focus:border-zinc-900 focus:ring-2 focus:ring-zinc-900/10 aria-[invalid=true]:border-red-400'

export default function AuthView({ settings, initialMode, onSession }: { settings: PlatformSettings; initialMode: Mode; onSession?: () => void }) {
  const [mode, setMode] = useState<Mode>(initialMode)

  useEffect(() => {
    setMode(initialMode)
  }, [initialMode])

  // check existing session — already logged in? go to dashboard
  useEffect(() => {
    if (mode !== 'login' && mode !== 'signup') return
    api<{ user: { role: string } | null }>('/api/auth/me')
      .then((d) => {
        if (d.user?.role === 'BOARD_MEMBER') navigate('/dashboard', true)
        else if (d.user?.role === 'SUPER_ADMIN') navigate('/master/dashboard', true)
      })
      .catch(() => {})
  }, [mode])

  function switchMode(m: Mode) {
    navigate(`/signup/etarnity/board-member${m === 'login' ? '' : `?mode=${m}`}`, true)
    setMode(m)
  }

  return (
    <section className="mx-auto flex w-full max-w-md flex-1 flex-col justify-center px-4 py-12 sm:px-6 sm:py-16" aria-label="Board member authentication">
      <motion.div
        key={mode}
        initial={{ opacity: 0, y: 16 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.4, ease: [0.22, 1, 0.36, 1] }}
        className="rounded-3xl border border-border/80 bg-white p-7 shadow-[0_20px_50px_-24px_rgba(24,24,27,0.2)] sm:p-9"
      >
        {mode === 'login' ? <LoginForm settings={settings} switchMode={switchMode} onSession={onSession} /> : null}
        {mode === 'signup' ? <SignupForm switchMode={switchMode} onSession={onSession} /> : null}
        {mode === 'forgot' ? <ForgotForm switchMode={switchMode} /> : null}
        {mode === 'reset' ? <ResetForm switchMode={switchMode} /> : null}
      </motion.div>

      <p className="mt-5 text-center text-[11px] leading-relaxed text-muted-foreground">
        <ShieldCheck className="mr-1 inline h-3.5 w-3.5 text-emerald-600" />
        Board member accounts are protected. Registration requires a valid invitation code generated by the Super Admin.
      </p>
      <p className="mt-2 text-center text-[11px] text-muted-foreground">
        <button type="button" onClick={() => navigate('/')} className="underline underline-offset-2 hover:text-foreground">
          Back to homepage
        </button>
      </p>
    </section>
  )
}

/* --------------------------------- Login --------------------------------- */

function LoginForm({ settings, switchMode, onSession }: { settings: PlatformSettings; switchMode: (m: Mode) => void; onSession?: () => void }) {
  const [email, setEmail] = useState('')
  const [password, setPassword] = useState('')
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [loading, setLoading] = useState(false)

  async function submit(e: React.FormEvent) {
    e.preventDefault()
    setLoading(true)
    setErrors({})
    try {
      const d = await api<{ redirect: string }>('/api/auth/login', { method: 'POST', body: { email, password } })
      toast.success('Welcome back!')
      onSession?.()
      navigate(d.redirect.replace('/#', ''))
    } catch (err) {
      const e2 = err as ApiError
      if (e2.fieldErrors) setErrors(e2.fieldErrors)
      else toast.error(e2.message)
    } finally {
      setLoading(false)
    }
  }

  return (
    <>
      <div className="text-center">
        <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-secondary">
          <LogIn className="h-5 w-5 text-muted-foreground" />
        </div>
        <h1 className="mt-4 text-xl font-bold tracking-tight">Board Member Login</h1>
        <p className="mt-1 text-sm text-muted-foreground">{settings.companyName}</p>
      </div>

      <form onSubmit={submit} noValidate className="mt-7 space-y-4">
        <div>
          <label className="mb-1.5 block text-xs font-semibold" htmlFor="login-email">Email</label>
          <input id="login-email" type="email" autoComplete="email" value={email} aria-invalid={!!errors.email} onChange={(e) => setEmail(e.target.value)} className={inputCls} placeholder="you@etarnity.com" />
          <FieldError message={errors.email} />
        </div>
        <div>
          <label className="mb-1.5 block text-xs font-semibold" htmlFor="login-password">Password</label>
          <input id="login-password" type="password" autoComplete="current-password" value={password} aria-invalid={!!errors.password} onChange={(e) => setPassword(e.target.value)} className={inputCls} placeholder="••••••••" />
          <FieldError message={errors.password} />
        </div>
        <button type="submit" disabled={loading} className="inline-flex h-11 w-full items-center justify-center rounded-xl bg-zinc-900 text-sm font-semibold text-white transition-all hover:bg-zinc-800 active:scale-[0.99] disabled:opacity-50">
          {loading ? 'Signing in…' : 'Sign in'}
        </button>
      </form>

      <div className="mt-5 flex items-center justify-between text-xs">
        <button type="button" onClick={() => switchMode('forgot')} className="font-medium text-muted-foreground underline underline-offset-2 hover:text-foreground">
          Forgot password?
        </button>
        <button type="button" onClick={() => switchMode('signup')} className="font-semibold text-zinc-900 underline underline-offset-2">
          Create account
        </button>
      </div>
    </>
  )
}

/* -------------------------------- Signup -------------------------------- */

function SignupForm({ switchMode, onSession }: { switchMode: (m: Mode) => void; onSession?: () => void }) {
  const [form, setForm] = useState({ invitationToken: '', fullName: '', email: '', password: '', confirmPassword: '' })
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [loading, setLoading] = useState(false)

  function setField(key: keyof typeof form, value: string) {
    setForm((f) => ({ ...f, [key]: value }))
    setErrors((e) => { const n = { ...e }; delete n[key]; return n })
  }

  async function submit(e: React.FormEvent) {
    e.preventDefault()
    setLoading(true)
    setErrors({})
    try {
      const d = await api<{ redirect: string }>('/api/auth/register', { method: 'POST', body: form })
      toast.success('Account created. Welcome to the board!')
      onSession?.()
      navigate(d.redirect.replace('/#', ''))
    } catch (err) {
      const e2 = err as ApiError
      if (e2.fieldErrors) setErrors(e2.fieldErrors)
      else toast.error(e2.message)
    } finally {
      setLoading(false)
    }
  }

  return (
    <>
      <div className="text-center">
        <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-secondary">
          <UserPlus className="h-5 w-5 text-muted-foreground" />
        </div>
        <h1 className="mt-4 text-xl font-bold tracking-tight">Board Member Registration</h1>
        <p className="mt-1 text-sm text-muted-foreground">Use the invitation code from the Super Admin.</p>
      </div>

      <form onSubmit={submit} noValidate className="mt-7 space-y-4">
        <div>
          <label className="mb-1.5 block text-xs font-semibold" htmlFor="inv-token">Invitation Code <span className="text-red-500">*</span></label>
          <input id="inv-token" type="text" value={form.invitationToken} aria-invalid={!!errors.invitationToken} onChange={(e) => setField('invitationToken', e.target.value.toLowerCase())} className={cn(inputCls, 'font-mono tracking-wide')} placeholder="e.g. a1b2c3d4e5" />
          <FieldError message={errors.invitationToken} />
        </div>
        <div>
          <label className="mb-1.5 block text-xs font-semibold" htmlFor="reg-name">Full Name <span className="text-red-500">*</span></label>
          <input id="reg-name" type="text" autoComplete="name" value={form.fullName} aria-invalid={!!errors.fullName} onChange={(e) => setField('fullName', e.target.value)} className={inputCls} placeholder="Your full name" />
          <FieldError message={errors.fullName} />
        </div>
        <div>
          <label className="mb-1.5 block text-xs font-semibold" htmlFor="reg-email">Email <span className="text-red-500">*</span></label>
          <input id="reg-email" type="email" autoComplete="email" value={form.email} aria-invalid={!!errors.email} onChange={(e) => setField('email', e.target.value)} className={inputCls} placeholder="you@etarnity.com" />
          <FieldError message={errors.email} />
        </div>
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <div>
            <label className="mb-1.5 block text-xs font-semibold" htmlFor="reg-pass">Password <span className="text-red-500">*</span></label>
            <input id="reg-pass" type="password" autoComplete="new-password" value={form.password} aria-invalid={!!errors.password} onChange={(e) => setField('password', e.target.value)} className={inputCls} placeholder="Min. 8 characters" />
            <FieldError message={errors.password} />
          </div>
          <div>
            <label className="mb-1.5 block text-xs font-semibold" htmlFor="reg-pass2">Confirm <span className="text-red-500">*</span></label>
            <input id="reg-pass2" type="password" autoComplete="new-password" value={form.confirmPassword} aria-invalid={!!errors.confirmPassword} onChange={(e) => setField('confirmPassword', e.target.value)} className={inputCls} placeholder="Repeat password" />
            <FieldError message={errors.confirmPassword} />
          </div>
        </div>
        <button type="submit" disabled={loading} className="inline-flex h-11 w-full items-center justify-center rounded-xl bg-zinc-900 text-sm font-semibold text-white transition-all hover:bg-zinc-800 active:scale-[0.99] disabled:opacity-50">
          {loading ? 'Creating account…' : 'Create account'}
        </button>
      </form>

      <p className="mt-4 flex items-start gap-1.5 rounded-lg border border-amber-200/70 bg-amber-50/60 p-3 text-[11px] leading-relaxed text-amber-900">
        <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" />
        Public registration is not allowed. If you do not have a code, contact the platform administrator.
      </p>

      <p className="mt-5 text-center text-xs">
        <button type="button" onClick={() => switchMode('login')} className="inline-flex items-center gap-1 font-semibold text-zinc-900 underline underline-offset-2">
          <ArrowLeft className="h-3.5 w-3.5" /> Back to login
        </button>
      </p>
    </>
  )
}

/* -------------------------------- Forgot -------------------------------- */

function ForgotForm({ switchMode }: { switchMode: (m: Mode) => void }) {
  const [email, setEmail] = useState('')
  const [loading, setLoading] = useState(false)
  const [sent, setSent] = useState<{ message: string; demoCode?: string } | null>(null)

  async function submit(e: React.FormEvent) {
    e.preventDefault()
    setLoading(true)
    try {
      const d = await api<{ message: string; demoResetCode?: string }>('/api/auth/forgot-password', { method: 'POST', body: { email } })
      setSent({ message: d.message, demoCode: d.demoResetCode })
      if (d.demoResetCode) toast.info('Reset code generated (demo environment).')
    } catch (err) {
      toast.error((err as ApiError).message)
    } finally {
      setLoading(false)
    }
  }

  return (
    <>
      <div className="text-center">
        <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-secondary">
          <MailQuestion className="h-5 w-5 text-muted-foreground" />
        </div>
        <h1 className="mt-4 text-xl font-bold tracking-tight">Forgot Password</h1>
        <p className="mt-1 text-sm text-muted-foreground">We will send a reset code to your email.</p>
      </div>

      {sent ? (
        <div className="mt-7 rounded-xl border border-emerald-200 bg-emerald-50 p-4 text-sm text-emerald-900">
          <p>{sent.message}</p>
          {sent.demoCode ? (
            <div className="mt-3 rounded-lg border border-emerald-300 bg-white p-3">
              <p className="text-[11px] font-semibold uppercase tracking-wider text-emerald-700">Demo reset code</p>
              <p className="mt-1 font-mono text-lg font-bold tracking-[0.2em]">{sent.demoCode}</p>
              <p className="mt-1 text-[11px] text-muted-foreground">
                In production this is only delivered by email (viewable in Admin → Emails). It expires in 30 minutes.
              </p>
            </div>
          ) : null}
          <button type="button" onClick={() => switchMode('reset')} className="mt-3 inline-flex items-center gap-1 font-semibold underline underline-offset-2">
            <KeyRound className="h-3.5 w-3.5" /> Enter reset code
          </button>
        </div>
      ) : (
        <form onSubmit={submit} noValidate className="mt-7 space-y-4">
          <div>
            <label className="mb-1.5 block text-xs font-semibold" htmlFor="fp-email">Email</label>
            <input id="fp-email" type="email" autoComplete="email" value={email} onChange={(e) => setEmail(e.target.value)} className={inputCls} placeholder="you@etarnity.com" required />
          </div>
          <button type="submit" disabled={loading} className="inline-flex h-11 w-full items-center justify-center rounded-xl bg-zinc-900 text-sm font-semibold text-white transition-all hover:bg-zinc-800 active:scale-[0.99] disabled:opacity-50">
            {loading ? 'Sending…' : 'Send reset code'}
          </button>
        </form>
      )}

      <p className="mt-5 text-center text-xs">
        <button type="button" onClick={() => switchMode('login')} className="inline-flex items-center gap-1 font-semibold text-zinc-900 underline underline-offset-2">
          <ArrowLeft className="h-3.5 w-3.5" /> Back to login
        </button>
      </p>
    </>
  )
}

